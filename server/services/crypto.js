import crypto from 'node:crypto';

// App passwords are stored encrypted (AES-256-GCM). The key is derived from JWT_SECRET,
// so set a strong JWT_SECRET in server/.env and never change it after connecting accounts.
const key = () => crypto.createHash('sha256').update(process.env.JWT_SECRET || 'dev-secret').digest();

export function encrypt(text) {
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv('aes-256-gcm', key(), iv);
  const enc = Buffer.concat([cipher.update(text, 'utf8'), cipher.final()]);
  return [iv, cipher.getAuthTag(), enc].map((b) => b.toString('base64')).join('.');
}

export function decrypt(payload) {
  const [iv, tag, enc] = payload.split('.').map((p) => Buffer.from(p, 'base64'));
  const decipher = crypto.createDecipheriv('aes-256-gcm', key(), iv);
  decipher.setAuthTag(tag);
  return Buffer.concat([decipher.update(enc), decipher.final()]).toString('utf8');
}
